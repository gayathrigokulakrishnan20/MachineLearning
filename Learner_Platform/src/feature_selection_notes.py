# Feature selection checklist
#
# Correlation is a starting point, not the final decision.
#
# Consider:
# 1. Correlation with target
# 2. Correlation between features / multicollinearity
# 3. Domain relevance
# 4. Data leakage
# 5. Missing-value behaviour
# 6. Model-based feature importance
# 7. Validation performance after selection
#
# Important:
# High correlation does not prove causation.
# Low correlation does not always mean a feature is useless.
# Non-linear models can capture relationships Pearson correlation misses.
